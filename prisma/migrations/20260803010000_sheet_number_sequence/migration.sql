-- รหัสแบบสอบถามออกโดยระบบตอนผู้คีย์เริ่มกรอก (Owner Decision 2026-08-03)
--
-- รูปแบบ: SK-<เลข 6 หลัก>  เช่น SK-000123
-- เดินหน้าอย่างเดียว ไม่รีเซ็ตตามปี — การรีเซ็ตโดยไม่มีตัวแยกรอบ (เช่น ปี) ในรหัส
-- จะทำให้เกิดรหัสซ้ำข้ามปีทันที จึงใช้ตัวนับเดียวตลอดอายุระบบ
--
-- ใช้ SEQUENCE ของ PostgreSQL เพราะรับประกันว่า nextval() ไม่คืนค่าซ้ำ
-- แม้มีผู้เรียกพร้อมกันจำนวนมาก โดย "ไม่ต้องล็อก" ต่างจากการอ่าน MAX()+1
--
-- MAXVALUE 999999 + NO CYCLE: เมื่อใช้ครบ nextval() จะ error ทันที
-- ไม่วนกลับไปออกเลขซ้ำ — ตั้งใจให้ระบบหยุดและแจ้งเตือน ดีกว่าออกรหัสชนเงียบ ๆ
--
-- หมายเหตุเรื่องเลขข้าม: รหัสถูกออกตอนกด "เริ่มกรอก" เพื่อให้ผู้คีย์เขียนลงกระดาษได้ทันที
-- ถ้าเริ่มแล้วไม่กรอกต่อ เลขนั้นจะหายไป (เช่น ...122 แล้วข้ามไป ...124) ซึ่งเป็นพฤติกรรม
-- ปกติของ SEQUENCE และไม่กระทบระบบ เพราะไม่ได้ใช้รหัสนับจำนวนเอกสาร

CREATE SEQUENCE IF NOT EXISTS "sheet_no_seq"
  AS bigint
  START WITH 1
  INCREMENT BY 1
  MINVALUE 1
  MAXVALUE 999999
  NO CYCLE;
